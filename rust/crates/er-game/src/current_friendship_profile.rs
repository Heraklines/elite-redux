//! Exact ordinary fresh GameData starter account seed catalog at pinned 399d.
//! The 570 literal keys/costs below come from starters.ts and SpeciesId; ER custom
//! keys come from the existing complete allSpecies progression export, not menus.
use std::collections::BTreeSet;
use er_state::current_friendship_profile::{CurrentFriendshipProfileError, CurrentFriendshipProfileV1, CURRENT_FRIENDSHIP_ORACLE_V1};
use er_types::{SafeU53, battle_ids::SpeciesId};
use crate::m9e_content_v2::PreparedGameContentV2;

// Two fresh-process complete allSpecies export, retained through generated recoil publication.
pub const QUALIFIED_COMPLETE_PROGRESSION_HASH: &str = "b167ad856885c95dab4f1e9cdf1456dd4924f6c4dbc8443e12918f232215192e";

pub fn seed_species(content: &PreparedGameContentV2) -> Result<Vec<SpeciesId>, CurrentFriendshipProfileError> {
    if content.identity().oracle_sha.as_str() != CURRENT_FRIENDSHIP_ORACLE_V1
        || content.identity().progression_hash.as_str() != QUALIFIED_COMPLETE_PROGRESSION_HASH
        || content.progression.pack().content_hash.as_str() != QUALIFIED_COMPLETE_PROGRESSION_HASH
    {
        return Err(CurrentFriendshipProfileError);
    }
    let mut keys = BTreeSet::new();
    for &(id, _) in PINNED_STARTER_COSTS {
        keys.insert(SpeciesId::new(SafeU53::new(u64::from(id)).map_err(|_| CurrentFriendshipProfileError)?));
    }
    for species in &content.progression.pack().species {
        if species.form == 0 && species.species.get().get() >= 10_000 {
            if !species.experience.as_ref().is_some_and(|metadata| matches!(metadata.source_form, er_progression::content_v2::ExperienceSourceFormV2::Species)) {
                return Err(CurrentFriendshipProfileError);
            }
            keys.insert(species.species);
        }
    }
    Ok(keys.into_iter().collect())
}

pub fn fresh_profile(content: &PreparedGameContentV2, owner_seat: er_types::SeatId) -> Result<CurrentFriendshipProfileV1, CurrentFriendshipProfileError> {
    CurrentFriendshipProfileV1::fresh(content.identity().clone(), seed_species(content)?, owner_seat)
}

