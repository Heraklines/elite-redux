#[cfg(test)]
mod tests {
    use super::*;
    use er_types::SafeU53;

    fn id<T: From<SafeU53>>(value: u64) -> T {
        T::from(SafeU53::new(value).expect("id"))
    }

    fn money(value: u64) -> Money {
        Money::new(SafeU53::new(value).expect("money"))
    }

    fn rules() -> RewardRuleSet {
        RewardRuleSet {
            supports_reroll: true,
            supports_locks: true,
            reroll_base_cost: money(250),
            lock_cost_tiers: vec![money(50), money(125), money(300), money(750), money(2000)],
            selected_modifier_keys: Vec::new(),
        }
    }

    fn offer(free: bool) -> RewardOfferView {
        RewardOfferView {
            offer_id: id(1),
            modifier_id: id(7),
            tier: ModifierTier::Common,
            price: if free { money(0) } else { money(300) },
            sold: false,
        }
    }

    #[test]
    fn free_select_requires_a_zero_price_offer() {
        let free = offer(true);
        assert_eq!(
            pay_for_offer(money(10), std::slice::from_ref(&free), free.offer_id, None),
            Ok(money(10))
        );
        assert_eq!(
            pay_for_offer(
                money(10),
                std::slice::from_ref(&free),
                free.offer_id,
                Some(money(0))
            ),
            Ok(money(10))
        );
        let paid = offer(false);
        assert_eq!(
            pay_for_offer(money(10), std::slice::from_ref(&paid), paid.offer_id, None),
            Err(ShopError::OfferNotFree)
        );
    }

    #[test]
    fn buy_charges_the_exact_listed_price() {
        let paid = offer(false);
        assert_eq!(
            pay_for_offer(
                money(1_000),
                std::slice::from_ref(&paid),
                paid.offer_id,
                Some(money(300))
            ),
            Ok(money(700))
        );
        assert_eq!(
            pay_for_offer(
                money(1_000),
                std::slice::from_ref(&paid),
                paid.offer_id,
                Some(money(299))
            ),
            Err(ShopError::PriceMismatch)
        );
        assert_eq!(
            pay_for_offer(
                money(299),
                std::slice::from_ref(&paid),
                paid.offer_id,
                Some(money(300))
            ),
            Err(ShopError::InsufficientMoney)
        );
    }

    #[test]
    fn reroll_costs_escalate_and_require_funds() {
        let (balance, count) = pay_for_reroll(money(1_000), &rules(), 0).expect("reroll 1");
        assert_eq!(balance.get().get(), 750);
        assert_eq!(count, 1);
        let (_, count2) = pay_for_reroll(balance, &rules(), count).expect("reroll 2");
        assert_eq!(count2, 2);
        assert_eq!(
            pay_for_reroll(money(100), &rules(), 0),
            Err(ShopError::InsufficientMoney)
        );
    }

    #[test]
    fn lock_arm_pays_schedule_disarm_is_free() {
        let armed =
            toggle_lock(money(1_000), &rules(), true, ModifierTier::Great, true).expect("arm");
        assert_eq!(armed.get().get(), 875);
        assert_eq!(
            toggle_lock(armed, &rules(), true, ModifierTier::Great, false).expect("disarm"),
            armed
        );
        assert_eq!(
            toggle_lock(money(1_000), &rules(), false, ModifierTier::Common, true),
            Err(ShopError::LockUnsupported)
        );
    }

    #[test]
    fn market_buy_decrements_and_derives_sold() {
        let stock = MarketStockView {
            stock_id: id(9),
            modifier_id: id(400),
            price: money(60),
            initial_quantity: 2,
            remaining_quantity: 2,
            sold: false,
        };
        let (balance, updated) = buy_stock(
            money(500),
            std::slice::from_ref(&stock),
            stock.stock_id,
            money(60),
        )
        .expect("buy");
        assert_eq!(balance.get().get(), 440);
        assert_eq!(updated.remaining_quantity, 1);
        assert!(!updated.sold);
        let (_, final_entry) = buy_stock(
            balance,
            std::slice::from_ref(&updated),
            stock.stock_id,
            money(60),
        )
        .expect("buy 2");
        assert!(final_entry.sold);
        assert_eq!(
            buy_stock(
                balance,
                std::slice::from_ref(&final_entry),
                stock.stock_id,
                money(60)
            ),
            Err(ShopError::StockDepleted)
        );
    }

    #[test]
    fn market_leave_rejects_shop_contaminated_rules() {
        let clean = MarketRuleSet {
            supports_reroll: false,
            supports_locks: false,
            maximum_stock_entries: 16,
            selected_modifier_keys: Vec::new(),
        };
        assert_eq!(leave_market(&clean), Ok(()));
    }
}
