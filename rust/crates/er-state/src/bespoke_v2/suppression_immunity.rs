/// Schema version of [`SuppressionImmunityStateV2`].
pub const SUPPRESSION_IMMUNITY_STATE_SCHEMA_VERSION: u32 = 1;

/// Frozen ceiling on stacked layers for one volatile/tag subject instance.
pub const VOLATILE_TAG_MAX_LAYERS: u8 = 8;

/// Frozen size of the classification closure in distinct behavior-unit
/// identities (unique provenance hashes).
pub const CLASSIFIED_BEHAVIOR_UNIT_HASHES: usize = 1002;

/// Frozen size of the classification closure in behavior units, counting the
/// mirrored active/passive slot identities separately.
///
/// Composition: `SUPPRESSION_UNUSUAL_IMMUNITY` 134, `STATUS_VOLATILE_TAG`
/// 910, `CUSTOM_DISPATCH` ability groups 360 (`ACTIVE_ABILITY` 180 +
/// `PASSIVE_ABILITY` 180), and the two handoff units from
/// `CHARGE_RECHARGE_LOCK` (`CHARGED` battler tag, `PorousChargeAbAttr`).
pub const CLASSIFIED_BEHAVIOR_UNITS: usize = 1406;

/// Closed addressing for the four ability slots of one battler: the active
/// slot first, then the three passive slots in fixed order.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum AbilitySlot {
    Active,
    Passive0,
    Passive1,
    Passive2,
}

impl AbilitySlot {
    /// Canonical slot order used by the dispatcher: active before passives.
    pub const ALL: [AbilitySlot; 4] = [
        AbilitySlot::Active,
        AbilitySlot::Passive0,
        AbilitySlot::Passive1,
        AbilitySlot::Passive2,
    ];

    /// Position in the frozen active-before-passive order.
    pub fn order(self) -> u8 {
        match self {
            AbilitySlot::Active => 0,
            AbilitySlot::Passive0 => 1,
            AbilitySlot::Passive1 => 2,
            AbilitySlot::Passive2 => 3,
        }
    }

    /// Index into the parallel `[Option<AbilityId>; 3]` passive arrays;
    /// `None` for the active slot.
    pub fn passive_index(self) -> Option<usize> {
        match self {
            AbilitySlot::Active => None,
            AbilitySlot::Passive0 => Some(0),
            AbilitySlot::Passive1 => Some(1),
            AbilitySlot::Passive2 => Some(2),
        }
    }
}

/// Closed kind of a live suppression overlay. Source scope is part of the
/// identity so overlapping suppressors stay distinguishable and precedence is
/// total.
#[derive(Clone, Debug, Eq, Hash, Ord, PartialEq, PartialOrd, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "SCREAMING_SNAKE_CASE", deny_unknown_fields)]
pub enum SuppressionOrigin {
    /// The battle-wide ignore-abilities switch.
    GlobalIgnore,
    /// A field ability suppressor (Neutralizing Gas family): scoped to the
    /// field source staying present.
    FieldAbility { source_pokemon: PokemonId },
    /// A move-applied per-target suppressor (Gastro Acid family): persists
    /// until the owner leaves the field or the effect is cleared.
    MoveApplied { source_move: MoveId },
}

impl SuppressionOrigin {
    /// Source-scoped precedence used when several suppressors cover one
    /// slot. Lower wins: the global switch outranks field abilities, which
    /// outrank move-applied overlays; ties break by creation ordinal.
    pub fn precedence(&self) -> u8 {
        match self {
            SuppressionOrigin::GlobalIgnore => 0,
            SuppressionOrigin::FieldAbility { .. } => 1,
            SuppressionOrigin::MoveApplied { .. } => 2,
        }
    }
}

/// One live suppression overlay on one battler's ability slot. The overlay
/// records full provenance (owner, slot, origin, creation ordinal) and never
/// touches the underlying ability identity.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SlotSuppressionEntryV2 {
    pub owner: PokemonId,
    pub slot: AbilitySlot,
    pub origin: SuppressionOrigin,
    pub creation_ordinal: SafeU53,
    /// Remaining timed window; `None` lasts until an explicit cleanup event
    /// or source removal. Zero is invalid.
    pub remaining_turns: Option<u16>,
}

impl SlotSuppressionEntryV2 {
    pub fn validate(&self) -> Result<(), SuppressionStateError> {
        if self.creation_ordinal == SafeU53::ZERO {
            return Err(SuppressionStateError::ZeroCreationOrdinal);
        }
        if self.remaining_turns == Some(0) {
            return Err(SuppressionStateError::ZeroRemainingTurns);
        }
        Ok(())
    }
}

/// Closed subject kinds admitted by the `STATUS_VOLATILE_TAG` cluster.
#[derive(Clone, Debug, Eq, Hash, Ord, PartialEq, PartialOrd, Serialize, Deserialize)]
#[serde(tag = "kind", rename_all = "SCREAMING_SNAKE_CASE", deny_unknown_fields)]
pub enum VolatileTagSubject {
    /// A major-status subject (poison, burn, ...).
    MajorStatus(StatusKind),
    /// A volatile status identified by its non-empty registry key.
    VolatileStatus { registry_key: String },
    /// A battler tag identified by its non-empty registry key.
    BattlerTag { registry_key: String },
    /// A side-scoped positional tag identified by its non-empty registry key.
    PositionalTag {
        side: BattleSide,
        registry_key: String,
    },
}

impl VolatileTagSubject {
    /// Deterministic subject-family order used for canonical instance
    /// storage: major statuses, volatiles, battler tags, positional tags.
    fn family_order(&self) -> u8 {
        match self {
            VolatileTagSubject::MajorStatus(_) => 0,
            VolatileTagSubject::VolatileStatus { .. } => 1,
            VolatileTagSubject::BattlerTag { .. } => 2,
            VolatileTagSubject::PositionalTag { .. } => 3,
        }
    }

    fn registry_key(&self) -> Option<&str> {
        match self {
            VolatileTagSubject::MajorStatus(_) => None,
            VolatileTagSubject::VolatileStatus { registry_key }
            | VolatileTagSubject::BattlerTag { registry_key }
            | VolatileTagSubject::PositionalTag { registry_key, .. } => Some(registry_key),
        }
    }
}

/// One admitted status/volatile/tag instance. Stacking instances collapse
/// into one entry with layered counts; provenance stays the admitting
/// behavior unit's creation ordinal.
#[derive(Clone, Debug, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct VolatileTagInstanceV2 {
    pub owner: PokemonId,
    pub subject: VolatileTagSubject,
    pub layers: u8,
    pub creation_ordinal: SafeU53,
    /// Remaining timed window; `None` lapses only through explicit cleanup.
    pub remaining_turns: Option<u16>,
}

impl VolatileTagInstanceV2 {
    pub fn validate(&self) -> Result<(), SuppressionStateError> {
        if self.layers == 0 {
            return Err(SuppressionStateError::ZeroLayers);
        }
        if self.layers > VOLATILE_TAG_MAX_LAYERS {
            return Err(SuppressionStateError::LayerOverflow {
                layers: self.layers,
                ceiling: VOLATILE_TAG_MAX_LAYERS,
            });
        }
        if self.creation_ordinal == SafeU53::ZERO {
            return Err(SuppressionStateError::ZeroCreationOrdinal);
        }
        if self.remaining_turns == Some(0) {
            return Err(SuppressionStateError::ZeroRemainingTurns);
        }
        if let Some(key) = self.subject.registry_key()
            && key.is_empty()
        {
            return Err(SuppressionStateError::EmptyRegistryKey);
        }
        Ok(())
    }
}

/// Canonical root for the suppression/unusual-immunity and volatile-tag
/// families. Entries are stored in frozen deterministic order:
///
/// - slot suppressions by `(owner, slot order, origin precedence, ordinal)`
/// - volatile tags by `(owner, subject family, subject identity, ordinal)`
#[derive(Clone, Debug, Default, Eq, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SuppressionImmunityStateV2 {
    pub schema_version: u32,
    pub next_creation_ordinal: SafeU53,
    pub slot_suppressions: Vec<SlotSuppressionEntryV2>,
    pub volatile_tags: Vec<VolatileTagInstanceV2>,
}

impl SuppressionImmunityStateV2 {
    pub fn new() -> Self {
        Self {
            schema_version: SUPPRESSION_IMMUNITY_STATE_SCHEMA_VERSION,
            next_creation_ordinal: SafeU53::new(1).unwrap_or(SafeU53::ZERO),
            slot_suppressions: Vec::new(),
            volatile_tags: Vec::new(),
        }
    }

    pub fn validate(&self) -> Result<(), SuppressionStateError> {
        if self.schema_version != SUPPRESSION_IMMUNITY_STATE_SCHEMA_VERSION {
            return Err(SuppressionStateError::SchemaVersion {
                expected: SUPPRESSION_IMMUNITY_STATE_SCHEMA_VERSION,
                actual: self.schema_version,
            });
        }
        if self.next_creation_ordinal == SafeU53::ZERO {
            return Err(SuppressionStateError::ZeroCreationOrdinal);
        }
        let mut ordinals = BTreeSet::new();
        let mut previous: Option<(u64, u8, u8, SafeU53)> = None;
        for entry in &self.slot_suppressions {
            entry.validate()?;
            if !ordinals.insert(entry.creation_ordinal) {
                return Err(SuppressionStateError::DuplicateCreationOrdinal);
            }
            if entry.creation_ordinal >= self.next_creation_ordinal {
                return Err(SuppressionStateError::NextCreationOrdinalNotAhead);
            }
            let key = (
                entry.owner.get().get(),
                entry.slot.order(),
                entry.origin.precedence(),
                entry.creation_ordinal,
            );
            if previous.is_some_and(|prior| prior >= key) {
                return Err(SuppressionStateError::SlotSuppressionsOutOfOrder);
            }
            previous = Some(key);
        }
        let mut previous_tag: Option<(u64, u8, String, SafeU53)> = None;
        for instance in &self.volatile_tags {
            instance.validate()?;
            if !ordinals.insert(instance.creation_ordinal) {
                return Err(SuppressionStateError::DuplicateCreationOrdinal);
            }
            if instance.creation_ordinal >= self.next_creation_ordinal {
                return Err(SuppressionStateError::NextCreationOrdinalNotAhead);
            }
            let key = (
                instance.owner.get().get(),
                instance.subject.family_order(),
                instance
                    .subject
                    .registry_key()
                    .unwrap_or_default()
                    .to_owned(),
                instance.creation_ordinal,
            );
            if previous_tag.is_some_and(|prior| prior >= key) {
                return Err(SuppressionStateError::VolatileTagsOutOfOrder);
            }
            previous_tag = Some(key);
        }
        Ok(())
    }

    /// Whether any suppression overlay covers `owner`'s `slot`.
    pub fn slot_is_suppressed(&self, owner: PokemonId, slot: AbilitySlot) -> bool {
        self.governing_origin(owner, slot).is_some()
    }

    /// Highest-precedence suppression origin covering the slot, ties broken
    /// by earliest creation ordinal. `None` means the slot acts unsuppressed.
    pub fn governing_origin(
        &self,
        owner: PokemonId,
        slot: AbilitySlot,
    ) -> Option<&SuppressionOrigin> {
        self.slot_suppressions
            .iter()
            .filter(|entry| entry.owner == owner && entry.slot == slot)
            .min_by_key(|entry| (entry.origin.precedence(), entry.creation_ordinal))
            .map(|entry| &entry.origin)
    }
}

/// Errors raised by canonical validation of the suppression/volatile-tag
/// state.
#[derive(Clone, Debug, Eq, Error, PartialEq)]
pub enum SuppressionStateError {
    #[error("suppression state schema version must be {expected}, got {actual}")]
    SchemaVersion { expected: u32, actual: u32 },
    #[error("suppression creation ordinals must be positive")]
    ZeroCreationOrdinal,
    #[error("remaining turns must be positive when present")]
    ZeroRemainingTurns,
    #[error("volatile tag layers must be positive")]
    ZeroLayers,
    #[error("volatile tag layer stack of {layers} exceeds the frozen ceiling of {ceiling}")]
    LayerOverflow { layers: u8, ceiling: u8 },
    #[error("volatile tag registry keys must not be empty")]
    EmptyRegistryKey,
    #[error("creation ordinals must be unique across suppressions and tags")]
    DuplicateCreationOrdinal,
    #[error("next creation ordinal must stay ahead of all live entries")]
    NextCreationOrdinalNotAhead,
    #[error("slot suppressions must be strictly ordered by owner, slot, precedence, ordinal")]
    SlotSuppressionsOutOfOrder,
    #[error("volatile tag instances must be strictly ordered by owner, subject, ordinal")]
    VolatileTagsOutOfOrder,
    #[error("behavior-unit provenance hash {hash} is outside the frozen classification closure")]
    UnknownBehaviorUnit { hash: String },
    #[error("provenance hash must be 64 lowercase hexadecimal characters")]
    MalformedProvenanceHash,
}

