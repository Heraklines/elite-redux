//! Canonical typed state for the M6C bespoke families owned by this module:
//! `SUPPRESSION_UNUSUAL_IMMUNITY` (ability-slot suppression overlays and
//! unusual-immunity identity), the `STATUS_VOLATILE_TAG` cluster (closed
//! typed status/volatile/battler-tag/positional-tag instances), and the
//! `CUSTOM_DISPATCH` ability groups (the closed custom ability dispatcher
//! covering every `ACTIVE_ABILITY`- and `PASSIVE_ABILITY`-sourced behavior
//! unit), plus the two handoff units from `CHARGE_RECHARGE_LOCK` (the
//! `CHARGED` battler-tag definition and the `PorousChargeAbAttr` fixed
//! dispatch).
//!
//! Every behavior unit in the frozen closure carries exactly one
//! [`DispatchClass`] resolved from the pinned semantic catalog; nothing in
//! the closure is unclassified and no unit degrades to an unsupported or
//! no-op residual. Suppression overlays record their full source-scoped
//! provenance and never rewrite an ability slot's identity: the owning
//! [`er_types::battle_model::AbilityLoadout`] keeps its original ids even
//! while suppressed, so unsupported abilities are never converted to NONE.
//!
//! All mutation happens through clone-stage-validate transitions owned by
//! `er-battle/src/m6/bespoke/suppression_immunity.rs`; this module supplies
//! the typed shapes, ordering invariants, validation, queries, and the
//! closed classification table.

