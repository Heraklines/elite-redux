/// Closed lane assigned to every behavior unit in the frozen closure. Each
/// lane has a defined decision surface in the battle-side dispatcher
/// (ordering, suppression gating, immunity/bypass interaction, and typed
/// routing evidence); no lane is unsupported and none stages a neutral or
/// no-op result.
#[derive(Clone, Copy, Debug, Eq, Hash, Ord, PartialEq, PartialOrd, Serialize, Deserialize)]
#[serde(rename_all = "SCREAMING_SNAKE_CASE")]
pub enum DispatchClass {
    /// Intrinsic subject definitions loaded at content load (major-status,
    /// battler-tag, and positional-tag identity definitions, including the
    /// handoff `CHARGED` tag).
    SubjectDefinition,
    /// Seeded RNG callsites bound to a behavior unit.
    RngCallsite,
    /// Stat-stage query/change modifiers.
    StatStageModifier,
    /// Status apply-or-block gates.
    StatusGate,
    /// Tag add/remove/refresh modifiers.
    TagModifier,
    /// Move/type modifiers.
    TypeModifier,
    /// Weather set/block modifiers.
    WeatherModifier,
    /// Terrain set/block modifiers.
    TerrainModifier,
    /// Heal effects.
    Heal,
    /// Immunity grants (type/move/status/tag/intimidate families).
    ImmunityGate,
    /// Interaction bypasses (Infiltrator, ignore-stat-stages, ability-bypass,
    /// speed-chance bypasses, contact ignores).
    InteractionBypass,
    /// Move-power query modifiers (power boosts, STAB/weight scaling).
    PowerQuery,
    /// Accuracy query modifiers.
    AccuracyQuery,
    /// Priority query modifiers.
    PriorityQuery,
    /// Critical-hit query modifiers.
    CriticalQuery,
    /// Hit-count query bounds (multi-hit ceilings).
    HitCountQuery,
    /// Effects executed on summon.
    PostSummonTrigger,
    /// Effects executed after defending against a hit (contact included),
    /// including the handoff `PorousChargeAbAttr` fixed dispatch.
    PostDefendTrigger,
    /// Pre-summon / pre-attack / pre-defend phase gates.
    PrePhaseTrigger,
    /// End-of-turn post-turn effects.
    TurnEndTrigger,
    /// Post-battle effects.
    PostBattleTrigger,
    /// Post-faint effects.
    PostFaintTrigger,
    /// After-move / executed-move / post-move-used effects.
    AfterMoveTrigger,
    /// Fusion restriction gate (`NoFusionAbilityAbAttr` family).
    FusionGate,
    /// Run-success/escape meta gate.
    EncounterRunGate,
    /// Double-battle encounter chance gate.
    DoubleBattleGate,
    /// PP increase modifiers.
    PpModifier,
}

