const BY_CLASS: ReadonlyMap<string, BrowseCategory> = (() => {
  const map = new Map<string, BrowseCategory>();
  for (const [category, names] of Object.entries(BLOCK_CATEGORY_LISTS) as [BrowseCategory, readonly string[]][]) {
    for (const name of names) {
      if (map.has(name)) {
        throw new Error(`the block "${name}" is listed in two browse categories`);
      }
      map.set(name, category);
    }
  }
  return map;
})();

/** The browse category of a class declaration, by class name, or `undefined` when it is not listed. */
export function blockCategoryFor(className: string): BrowseCategory | undefined {
  return BY_CLASS.get(className) ?? BY_CLASS.get(className.replace(/AbAttr$/, ""));
}

/** The short names of the table (a test checks them against the declared classes). */
export function blockCategoryNames(): string[] {
  return [...BY_CLASS.keys()];
}
