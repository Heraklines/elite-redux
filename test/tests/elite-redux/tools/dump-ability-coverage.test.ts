// One-off report writer (NOT a gate): lists, per ability of the game, every attr that is not yet a fully library-built part.
// Run with:
//   ER_WRITE_ABILITY_COVERAGE=1 npx vitest run test/tests/elite-redux/tools/dump-ability-coverage.test.ts
// Output: requests/ABILITY-COVERAGE.md. It only READS the declarations and bindings that humans wrote and classifies them with the
// same classifyAttr the coverage gate uses; it never declares, binds or labels anything.
//
// Ability classes (an ability lands in the first that applies):
//   uncovered         at least one attr belongs to a class nobody declared
//   legacy-closure    at least one attr keeps a legacy closure or has a condition slot without any binding
//   package           at least one attr is a package (a declared part the library has no effect for yet) and nothing is uncovered or
//                     legacy-closure
//   fully decomposed  every attr is declared, every condition slot is bound to library atoms, no part is a package (an engine-query
//                     role counts as covered)
import { getBinding } from "#data/elite-redux/ability-studio/bindings";
import { declRegistry } from "#data/elite-redux/ability-studio/decl-registry";
import { isAbsentOptional } from "#data/elite-redux/ability-studio/define-decl";
import { classifyAttr } from "#test/tests/elite-redux/decomp/harness/coverage";
import { allAttrSites, liveAbilities } from "#test/tests/elite-redux/decomp/harness/sites";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { describe, expect, it } from "vitest";

type AbilityClass = "uncovered" | "legacy-closure" | "package" | "fully decomposed";

describe("ability coverage report", () => {
  it.skipIf(process.env.ER_WRITE_ABILITY_COVERAGE !== "1")("writes requests/ABILITY-COVERAGE.md", () => {
    const sites = allAttrSites();
    const perAbility = new Map<number, { name: string; notes: { cls: AbilityClass; text: string }[]; attrs: number }>();
    for (const ability of liveAbilities()) {
      perAbility.set(ability.id, { name: ability.name, notes: [], attrs: 0 });
    }
    for (const site of sites) {
      const entry = perAbility.get(site.abilityId);
      if (entry === undefined) {
        continue;
      }
      entry.attrs++;
      const module = declRegistry.get(site.className);
      if (module === undefined || module.decl.status === "todo") {
        entry.notes.push({ cls: "uncovered", text: `attr ${site.attrIndex} ${site.className}: no declaration` });
        continue;
      }
      const result = classifyAttr(site, module);
      for (const slot of module.decl.conditions) {
        if (isAbsentOptional(site.attr, slot)) {
          continue;
        }
        const binding = getBinding(site.abilityId, site.attrIndex, slot.slot);
        if (binding === undefined) {
          entry.notes.push({
            cls: "legacy-closure",
            text: `attr ${site.attrIndex} ${site.className}: condition slot ${slot.slot} has no binding`,
          });
        } else if (binding.legacyClosure !== undefined) {
          entry.notes.push({
            cls: "legacy-closure",
            text: `attr ${site.attrIndex} ${site.className}: condition slot ${slot.slot} is a legacy closure`,
          });
        }
      }
      const effectIsPackage = (module.decl as { effect?: { id?: string } }).effect?.id === "effect.package";
      if (result.bucket === "packageOnly" || effectIsPackage) {
        entry.notes.push({
          cls: "package",
          text: `attr ${site.attrIndex} ${site.className}: ${
            result.bucket === "packageOnly" && module.decl.kind !== "package"
              ? "exempt"
              : "package (the library has no effect block for it yet)"
          }`,
        });
      }
    }
    const order: AbilityClass[] = ["uncovered", "legacy-closure", "package", "fully decomposed"];
    const groups: Record<AbilityClass, { id: number; name: string; notes: string[] }[]> = {
      uncovered: [],
      "legacy-closure": [],
      package: [],
      "fully decomposed": [],
    };
    let noAttrs = 0;
    for (const [id, entry] of [...perAbility.entries()].sort((a, b) => a[0] - b[0])) {
      if (entry.attrs === 0) {
        noAttrs++;
        continue;
      }
      const cls = order.find(c => entry.notes.some(n => n.cls === c)) ?? "fully decomposed";
      groups[cls].push({ id, name: entry.name, notes: entry.notes.map(n => n.text) });
    }
    const total = [...perAbility.values()].filter(e => e.attrs > 0).length;
    const lines: string[] = [];
    lines.push("# Ability coverage (every attr of every ability)");
    lines.push("");
    lines.push(
      "Generated by `test/tests/elite-redux/tools/dump-ability-coverage.test.ts` (ER_WRITE_ABILITY_COVERAGE=1). It only reads the",
    );
    lines.push("declarations and bindings; nothing in this list was declared or bound by a script.");
    lines.push("");
    lines.push(`Abilities with at least one attr: ${total} (plus ${noAttrs} without any attr).`);
    lines.push("");
    lines.push("| Class | Abilities |");
    lines.push("| --- | ---: |");
    for (const cls of ["fully decomposed", "package", "legacy-closure", "uncovered"] as const) {
      lines.push(
        `| ${cls === "package" ? "with package parts" : cls === "legacy-closure" ? "with legacy-closure parts (or an unbound condition)" : cls === "uncovered" ? "uncovered (an attr of an undeclared class)" : cls} | ${groups[cls].length} |`,
      );
    }
    lines.push("");
    lines.push(
      "Rules: an ability lands in the first class that applies (uncovered, then legacy-closure, then package). A package is a",
    );
    lines.push(
      "declared part for which the library has no effect block yet; a legacy closure keeps the class's own condition code until an",
    );
    lines.push(
      "atom exists. Engine-query roles count as covered. Residual guards, feasibility lines and Tier C classes do not move an ability",
    );
    lines.push(
      "out of 'fully decomposed' here because they are declared and bound; they are listed per class in decomp-coverage.json.",
    );
    lines.push("");
    for (const cls of ["uncovered", "legacy-closure", "package"] as const) {
      lines.push(
        `## ${cls === "uncovered" ? "Uncovered" : cls === "legacy-closure" ? "Legacy-closure or unbound parts" : "Package parts only"} (${groups[cls].length})`,
      );
      lines.push("");
      for (const g of groups[cls]) {
        const uniq = [...new Set(g.notes)];
        lines.push(`- ${g.name} (${g.id}): ${uniq.join("; ")}`);
      }
      lines.push("");
    }
    lines.push(`## Fully decomposed (${groups["fully decomposed"].length})`);
    lines.push("");
    lines.push(groups["fully decomposed"].map(g => `${g.name} (${g.id})`).join(", "));
    lines.push("");
    writeFileSync(resolve(process.cwd(), "requests/ABILITY-COVERAGE.md"), lines.join("\n"), "utf8");
    console.log(
      `DECOMP_ABILITY_COVERAGE full=${groups["fully decomposed"].length} package=${groups.package.length} legacy=${groups["legacy-closure"].length} uncovered=${groups.uncovered.length} noAttrs=${noAttrs}`,
    );
    expect(total).toBeGreaterThan(1200);
  });
});
