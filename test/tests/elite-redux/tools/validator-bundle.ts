// Bundles the worker-safe validator core (vocabulary/validate-core.ts and its three pure siblings) into ONE
// plain ES module for the AI container, which cannot import TypeScript. The catalog writer writes the result
// to workers/er-ability-ai/container/validate-composition.mjs; catalog.test.ts regenerates it and fails when the
// committed copy differs, so the container validates with exactly the code the game and the editor worker use.
//
// esbuild runs in a child process: vitest's jsdom environment breaks esbuild's TextEncoder self-check.

import { execFileSync } from "node:child_process";
import { createRequire } from "node:module";
import { resolve } from "node:path";

const ENTRY = "src/data/elite-redux/ability-studio/vocabulary/validate-core.ts";

const BANNER = `// GENERATED by test/tests/elite-redux/tools/catalog-writer.ts (ER_WRITE_CATALOG=1 or dump-editor-data.test.ts). Do not edit.
// Source: ${ENTRY} (+ params.ts, slots.ts, composition-types.ts). Bundled with esbuild.
`;

const SCRIPT = `
const esbuild = require(process.argv[1]);
const result = esbuild.buildSync({
  entryPoints: [process.argv[2]],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  write: false,
  legalComments: "none",
  logLevel: "silent",
});
process.stdout.write(result.outputFiles[0].text);
`;

export function bundleValidator(root = process.cwd()): string {
  const viteRequire = createRequire(resolve(root, "package.json"));
  const esbuildPath = createRequire(viteRequire.resolve("vite")).resolve("esbuild");
  const text = execFileSync(process.execPath, ["-e", SCRIPT, esbuildPath, resolve(root, ENTRY)], {
    encoding: "utf8",
    maxBuffer: 16 * 1024 * 1024,
  });
  return `${BANNER}${text}`;
}

